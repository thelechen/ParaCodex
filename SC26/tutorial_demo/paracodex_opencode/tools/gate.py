#!/usr/bin/env python3
"""Independent correctness gate for the SC26 ParaCodex-style OpenCode tutorial.

No model APIs. Compiles and executes only local C++ files under this tutorial folder.
Do not run generated code outside an appropriately isolated, trusted environment.
"""
import argparse
import difflib
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "work"
RUNS = ROOT / "runs" / "latest"
GOLD = ROOT / "reference.cpp"
CAND = WORK / "candidate.cpp"
EXPECTED_SHA = "3a9792ec4bdf8dcff68f2a06a88773c777ea0ebf6357b969705c245a2bc959f6"
TESTS = [(5,7,0),(5,7,1),(7,9,3),(13,15,7),(17,23,13),(37,29,5)]
MAX_LOG = 500000


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def ensure_golden():
    actual = hashlib.sha256(GOLD.read_bytes()).hexdigest()
    if actual != EXPECTED_SHA:
        raise RuntimeError("Golden reference.cpp hash changed. Restore original tutorial files before running.")


def compiler_cmd():
    specified = os.environ.get("CXX", "g++")
    # Support CXX='g++-14' or CXX='clang++'. For flags use CXXFLAGS separately.
    if not shutil.which(specified):
        raise RuntimeError(f"C++ compiler not found: {specified}. Install g++ or set CXX to a supported compiler.")
    return specified


def run_command(args, timeout=40, env=None):
    try:
        proc = subprocess.run(args, cwd=ROOT, capture_output=True, text=True,
                              timeout=timeout, env=env)
        return {"command": args, "returncode": proc.returncode,
                "stdout": proc.stdout[:MAX_LOG], "stderr": proc.stderr[:MAX_LOG], "timed_out": False}
    except subprocess.TimeoutExpired as ex:
        return {"command": args, "returncode": 124, "stdout": str(ex.stdout or "")[:MAX_LOG],
                "stderr": str(ex.stderr or "")[:MAX_LOG], "timed_out": True}


def compile_one(source, output, want_openmp):
    cc = compiler_cmd()
    base = [cc,"-O2","-std=c++17"]
    if want_openmp:
        base += ["-fopenmp"]
    cmd = base + [str(source),"-o",str(output)]
    result = run_command(cmd, timeout=50)
    result["openmp_enabled"] = bool(want_openmp and result["returncode"] == 0)
    if want_openmp and result["returncode"] != 0:
        err = result["stderr"].lower()
        bad_flag = any(x in err for x in ["unsupported option '-fopenmp'", "unrecognized command-line option '-fopenmp'", "unsupported option '-fopenmp'", "libomp", "omp.h", "unknown argument: '-fopenmp'", "unable to find library -lomp"])
        if bad_flag:
            fallback = run_command([cc,"-O2","-std=c++17",str(source),"-o",str(output)],timeout=50)
            if fallback["returncode"] == 0:
                fallback["openmp_enabled"] = False
                fallback["warning"] = "OpenMP unavailable in this C++ compiler: compiled in SERIAL FALLBACK; performance claims disabled. Original error: "+result["stderr"][:600]
                return fallback
    return result


def parse_grid(txt, dims):
    tokens = txt.strip().split()
    if len(tokens) < 4 or tokens[0] != "GRID":
        raise ValueError("Missing GRID header")
    if tuple(int(x) for x in tokens[1:4]) != dims:
        raise ValueError("Wrong grid dimensions in output")
    n = dims[0]*dims[1]
    if len(tokens) != 4+n:
        raise ValueError(f"Expected {n} grid values but got {len(tokens)-4}")
    a = [float(s) for s in tokens[4:]]
    if not all(math.isfinite(v) for v in a):
        raise ValueError("Non-finite grid value")
    return a


def init(mode):
    ensure_golden()
    WORK.mkdir(parents=True,exist_ok=True)
    if RUNS.exists():
        shutil.rmtree(RUNS)
    (RUNS/"build").mkdir(parents=True)
    if mode == "repair":
        shutil.copyfile(ROOT/"buggy_candidate.cpp",CAND)
        description = "Intentional tutorial bug; this candidate was NOT generated by an LLM."
    else:
        shutil.copyfile(GOLD,CAND)
        description = "Serial reference copied as initial workspace; OpenCode must parallelize the loop nest."
    atomic_write(WORK/"session.md", "# SC26 ParaCodex-style tutorial session\n\n"+description+"\n")
    for n in ["analysis.md", "data_plan.md", "solver_notes.md", "reviewer_feedback.md", "optimization_plan.md", "correctness_verification.md"]:
        f=WORK/n
        if f.exists():f.unlink()
    print(f"INIT {mode}: {CAND.relative_to(ROOT)}. {description}")


def verify():
    ensure_golden()
    if not CAND.exists():
        raise RuntimeError("Run init first; missing work/candidate.cpp")
    (RUNS/"build").mkdir(parents=True,exist_ok=True)
    attempts = sorted(RUNS.glob("attempt_*.json"))
    n=len(attempts)+1
    if n > 10:
        raise RuntimeError("Ten attempts maximum; rerun init to start a new session.")
    baseline_bin = RUNS/"build"/"reference"
    candidate_bin = RUNS/"build"/"candidate"
    base_compile = compile_one(GOLD,baseline_bin,False)
    cand_compile = compile_one(CAND,candidate_bin,True)
    record={"attempt":n,"reference_compile":base_compile,"candidate_compile":cand_compile,
            "checks":[],"candidate_sha256":hashlib.sha256(CAND.read_bytes()).hexdigest(),
            "parallel_directive_found":bool(re.search(r"#\s*pragma\s+omp\s+parallel\s+for",CAND.read_text())),
            "openmp_enabled":cand_compile.get("openmp_enabled",False)}
    shutil.copyfile(CAND,RUNS/f"candidate_attempt_{n:02d}.cpp")
    if base_compile["returncode"] and not cand_compile["returncode"]:
        record["error"]="Reference compilation failed; cannot verify candidate"
    if base_compile["returncode"] != 0 or cand_compile["returncode"] != 0:
        record["status"]="FAIL_COMPILE"
    else:
        for dims in TESTS:
            env1=os.environ.copy();env1["OMP_NUM_THREADS"]="1"
            gr=run_command([str(baseline_bin),*map(str,dims),"dump"],timeout=20,env=env1)
            for threads in [1,2,4]:
                env=os.environ.copy();env["OMP_NUM_THREADS"]=str(threads)
                out=run_command([str(candidate_bin),*map(str,dims),"dump"],timeout=20,env=env)
                check={"dims":dims,"threads":threads,"reference_exit":gr["returncode"],
                       "candidate_exit":out["returncode"],"candidate_stderr":out["stderr"][:600]}
                if out["returncode"] != 0 or gr["returncode"] != 0:
                    check.update({"pass":False,"message":"Nonzero exit or timeout"})
                else:
                    try:
                        expect = parse_grid(gr["stdout"],dims)
                        got = parse_grid(out["stdout"],dims)
                        errors=[(i,abs(a-b)) for i,(a,b) in enumerate(zip(expect,got))
                                if not math.isclose(a,b,rel_tol=1e-8,abs_tol=1e-9)]
                        if errors:
                            ix,dist=errors[0]
                            check.update({"pass":False,"message":f"Mismatch at (x={ix%dims[0]},y={ix//dims[0]}), expected={expect[ix]:.12f}, got={got[ix]:.12f}, abs_error={dist:.3g}", "mismatch_count":len(errors)})
                        else:
                            check.update({"pass":True,"message":"All grid elements numerically equivalent"})
                    except Exception as ex:
                        check.update({"pass":False,"message":str(ex)})
                record["checks"].append(check)
        failures=[x for x in record["checks"] if not x["pass"]]
        record["status"]="FAIL_NUMERICS" if failures else "PASS_NUMERICS"
    record["parallel_status"]=("OPENMP_ACTIVE" if record["parallel_directive_found"] and record["openmp_enabled"] else "NOT_PROVEN_PARALLEL")
    atomic_write(RUNS/f"attempt_{n:02d}.json", json.dumps(record,indent=2)+"\n")
    summary=[f"ATTEMPT {n}: {record['status']}",f"PARALLEL: {record['parallel_status']}",
             f"Candidate compile exit={cand_compile['returncode']}"]
    if cand_compile.get("warning"):summary.append("WARNING: "+cand_compile["warning"][:300])
    fails=[x for x in record["checks"] if not x["pass"]]
    if fails:
        summary.extend("FAIL "+str(x["dims"])+f" threads={x['threads']}: "+x["message"] for x in fails[:8])
    else:
        summary.append(f"Passed {len(record['checks'])} checks including OMP_NUM_THREADS=1,2,4")
    msg="\n".join(summary)+"\n"
    atomic_write(RUNS/f"attempt_{n:02d}_summary.txt",msg)
    print(msg)
    return 0 if record["status"] == "PASS_NUMERICS" and record["parallel_status"] == "OPENMP_ACTIVE" else 1


def bench():
    ensure_golden()
    attempts=sorted(RUNS.glob('attempt_*.json'))
    if not attempts:raise RuntimeError('Run verify first')
    last=json.loads(attempts[-1].read_text())
    if last['status']!='PASS_NUMERICS':
        raise RuntimeError('No passing correctness gate; performance benchmarking forbidden')
    if not last['openmp_enabled']:
        raise RuntimeError('OpenMP unavailable: CPU fallback only; no parallel speedup can be reported')
    if not last['parallel_directive_found']:
        raise RuntimeError('No OpenMP pragma detected; parallelism not established')
    baseline=RUNS/'build'/'reference';candidate=RUNS/'build'/'candidate'
    measurements=[]
    for size,steps in [(384,35),(640,50)]:
        for t in [1,2,4]:
            ts=[];cs=[]
            for exe,tag in [(baseline,'reference'),(candidate,'candidate')]:
                for rep in range(3):
                    env=os.environ.copy();env['OMP_NUM_THREADS']=str(t)
                    res=run_command([str(exe),str(size),str(size),str(steps),'summary'],timeout=45,env=env)
                    found=re.search(r'TIME_MS\s+([0-9.eE+-]+)',res['stdout'])
                    checksum=re.search(r'CHECKSUM\s+([0-9.eE+-]+)',res['stdout'])
                    if res['returncode'] or not found or not checksum:
                        raise RuntimeError(f'Failed performance execution {tag}: {res["stderr"][:300]}')
                    measurements.append({"size":size,"steps":steps,"threads":t,"kind":tag,
                                         "repeat":rep+1,"time_ms":float(found.group(1)),"checksum":float(checksum.group(1))})
    report={"status":"MEASURED","note":"Wall-clock kernel-loop time only, not GPU profiling; CPU hardware/noise strongly influence speedup.",
            "raw":measurements,"summary":[]}
    from statistics import median
    for size in [384,640]:
        base_times=[x['time_ms'] for x in measurements if x['size']==size and x['kind']=='reference' and x['threads']==1]
        base=median(base_times)
        for t in [1,2,4]:
            vals=[x['time_ms'] for x in measurements if x['size']==size and x['kind']=='candidate' and x['threads']==t]
            cs=[x['checksum'] for x in measurements if x['size']==size and x['kind']=='candidate' and x['threads']==t]
            gr=[x['checksum'] for x in measurements if x['size']==size and x['kind']=='reference' and x['threads']==1]
            valid=math.isclose(median(cs),median(gr),rel_tol=1e-8,abs_tol=1e-6)
            report['summary'].append({"size":size,"threads":t,"baseline_ms":base,
                                      "candidate_ms":median(vals),"speedup":base/median(vals) if median(vals)>0 else None,
                                      "checksum_match":valid})
    atomic_write(RUNS/'performance.json',json.dumps(report,indent=2)+'\n')
    lines=['CPU timings; GPU timings are NOT measured here.']
    for x in report['summary']:
        lines.append(f"{x['size']}x{x['size']}, {x['threads']} thread(s): "
                     f"baseline {x['baseline_ms']:.3f} ms; candidate {x['candidate_ms']:.3f} ms; "
                     f"speedup {x['speedup']:.2f}x; checksum_match={x['checksum_match']}")
    print('\n'.join(lines))


def report():
    RUNS.mkdir(parents=True,exist_ok=True)
    parts=["# ParaCodex-style OpenCode teaching transcript", "", 
           "> This is generated from saved local artifacts and actual compiler/test outputs. It is NOT a full OpenCode session export.",""]
    for file,title in [(WORK/'session.md','Session'),(WORK/'analysis.md','Analyzer: loop analysis'),
                       (WORK/'data_plan.md','Analyzer: data/dependency plan'),
                       (WORK/'solver_notes.md','Solver: implementation notes'),
                       (WORK/'reviewer_feedback.md','Reviewer: failure diagnosis'),
                       (WORK/'optimization_plan.md','Performance plan'),
                       (WORK/'correctness_verification.md','Correctness verification')]:
        if file.exists():
            parts += ['## '+title,'',file.read_text()[:12000],'']
    for p in sorted(RUNS.glob('attempt_*.json')):
        rec=json.loads(p.read_text())
        parts += [f"## Tool gate: Attempt {rec['attempt']}","",f"- Result: {rec['status']}",
                  f"- Parallel: {rec['parallel_status']}",
                  f"- Compilation: {rec['candidate_compile']['command']}",
                  f"- stderr: `{rec['candidate_compile']['stderr'][:700]}`",'']
        for c in rec.get('checks',[]):
            if not c['pass']:parts += [f"- FAIL: {c['dims']} threads={c['threads']}: {c['message']}"]
        parts += ['']
    if (RUNS/'performance.json').exists():
        parts += ['## Measured CPU performance','',json.dumps(json.loads((RUNS/'performance.json').read_text())['summary'],indent=2),'']
    atomic_write(RUNS/'transcript.md','\n'.join(parts)+'\n')
    print('Saved '+str((RUNS/'transcript.md').relative_to(ROOT)))


def main():
    p=argparse.ArgumentParser(description=__doc__)
    sp=p.add_subparsers(dest='action',required=True)
    i=sp.add_parser('init');i.add_argument('--mode',choices=('normal','repair'),default='normal')
    sp.add_parser('verify');sp.add_parser('bench');sp.add_parser('report')
    args=p.parse_args()
    if args.action=='init':init(args.mode)
    elif args.action=='verify':return verify()
    elif args.action=='bench':bench()
    elif args.action=='report':report()
    return 0


if __name__=='__main__':
    try:sys.exit(main())
    except Exception as ex:
        print('ERROR: '+str(ex),file=sys.stderr)
        sys.exit(2)
